export function slugify(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export const SEED_EXERCISES: Exercise[] = RAW.map(([name, primaryMuscle, equipment]) => ({
  id: `seed-${slugify(name)}`,
  name,
  primaryMuscle,
  equipment,
  isCustom: false,
  createdAt: 0,
}));
